import { useMemo, useState } from 'react';
import { FileText, Plus, Send, PackageCheck, X, Sparkles, Truck, Building2, Trash2, RefreshCw, Clock, Wallet } from 'lucide-react';
import toast from 'react-hot-toast';
import Button from '@/components/ui/Button';
import Modal from '@/components/ui/Modal';
import Drawer from '@/components/ui/Drawer';
import PageHeader from '@/components/ui/PageHeader';
import StatCard from '@/components/ui/StatCard';
import StatusBadge from '@/components/ui/StatusBadge';
import EmptyState from '@/components/ui/EmptyState';
import { DetailHero, DetailSection, DetailField, DetailGrid } from '@/components/ui/Detail';
import DataTable, { type Column } from '@/components/table/DataTable';
import FilterChip from '@/components/table/FilterChip';
import ExportMenu from '@/components/table/ExportMenu';
import api from '@/services/api';
import { useList } from '@/hooks/useList';
import { formatDate } from '@/utils/formatters';
import { statusLabel } from '@/utils/status';

const rwf = (v: unknown) => `RWF ${Math.round(Number(v || 0)).toLocaleString()}`;
type Line = { itemId: string; quantity: number; unitCost: number };

export default function Purchasing() {
  const [tab, setTab] = useState<'orders' | 'suppliers'>('orders');
  const { rows: pos, loading, refresh } = useList<any>('purchase-orders', '/purchase-orders');
  const { rows: suppliers, loading: loadingSuppliers, refresh: refreshSuppliers } = useList<any>('suppliers', '/suppliers');
  const { rows: warehouses } = useList<any>('warehouses', '/warehouses');
  const { rows: items } = useList<any>('inventory', '/inventory');
  const [status, setStatus] = useState('');
  const [viewId, setViewId] = useState<number | null>(null);
  const [showCreate, setShowCreate] = useState(false);
  const [receiving, setReceiving] = useState<any>(null);
  const [expiry, setExpiry] = useState<Record<number, string>>({});
  const [form, setForm] = useState<{ supplierId: string; warehouseId: string; expectedDate: string; notes: string; lines: Line[] }>({ supplierId: '', warehouseId: '', expectedDate: '', notes: '', lines: [{ itemId: '', quantity: 10, unitCost: 0 }] });
  const [showSupplier, setShowSupplier] = useState(false);
  const [supplierForm, setSupplierForm] = useState({ name: '', contactName: '', email: '', phone: '', address: '', leadTimeDays: '7' });

  const filtered = useMemo(() => pos.filter((p) => !status || p.status === status), [pos, status]);
  const viewing = pos.find((p) => p.id === viewId) || null;
  const total = form.lines.reduce((s, l) => s + l.quantity * l.unitCost, 0);

  const post = async (url: string, body: unknown, ok: string) => {
    const res = await api.post(url, body);
    if (res.data?.success) {
      toast.success(res.data?.message || ok);
      refresh();
      refreshSuppliers();
      return res.data;
    }
    toast.error(res.data?.error?.message || 'Something went wrong');
    return null;
  };

  const createPO = async () => {
    const lines = form.lines.filter((l) => l.itemId && l.quantity > 0);
    if (!form.supplierId || !lines.length) return toast.error('Choose a supplier and at least one item');
    const ok = await post('/purchase-orders', { ...form, lines: undefined, items: lines.map((l) => ({ ...l, itemId: Number(l.itemId) })), supplierId: Number(form.supplierId), warehouseId: form.warehouseId ? Number(form.warehouseId) : undefined, expectedDate: form.expectedDate || undefined }, 'Purchase order created');
    if (ok) {
      setShowCreate(false);
      setForm({ supplierId: '', warehouseId: '', expectedDate: '', notes: '', lines: [{ itemId: '', quantity: 10, unitCost: 0 }] });
    }
  };

  const receive = async () => {
    const lines = receiving.items.map((l: any) => ({ itemId: l.itemId, receivedQuantity: l.quantity - l.receivedQuantity, expiryDate: expiry[l.itemId] || undefined }));
    if (await post(`/purchase-orders/${receiving.id}/receive`, { lines }, `${receiving.poNumber} received — stock updated`)) {
      setReceiving(null);
      setExpiry({});
    }
  };

  const addSupplier = async () => {
    if (!supplierForm.name.trim()) return toast.error('Enter the supplier name');
    if (await post('/suppliers', { ...supplierForm, leadTimeDays: Number(supplierForm.leadTimeDays) || 7 }, 'Supplier added')) {
      setShowSupplier(false);
      setSupplierForm({ name: '', contactName: '', email: '', phone: '', address: '', leadTimeDays: '7' });
    }
  };

  const poColumns: Column<any>[] = [
    { id: 'number', header: 'PO', required: true, accessor: (p) => p.poNumber, cell: (p) => <div><p className="flex items-center gap-1.5 font-semibold text-gray-900">{p.poNumber}{p.autoGenerated && <Sparkles className="h-3.5 w-3.5 text-accent-500" />}</p><p className="text-xs text-gray-500">{formatDate(p.createdAt)}</p></div> },
    { id: 'supplier', header: 'Supplier', accessor: (p) => p.supplier?.name },
    { id: 'status', header: 'Status', accessor: (p) => p.status, cell: (p) => <StatusBadge status={p.status} /> },
    { id: 'items', header: 'Items', align: 'right', accessor: (p) => p.items.length },
    { id: 'total', header: 'Total', align: 'right', accessor: (p) => Number(p.totalAmount), cell: (p) => <span className="font-semibold">{rwf(p.totalAmount)}</span> },
    { id: 'expected', header: 'Expected', accessor: (p) => (p.expectedDate ? new Date(p.expectedDate) : null), cell: (p) => <span className={p.expectedDate && new Date(p.expectedDate) < new Date() && ['DRAFT', 'SENT'].includes(p.status) ? 'font-semibold text-error-600' : 'text-gray-600'}>{p.expectedDate ? formatDate(p.expectedDate) : '—'}</span> },
    { id: 'warehouse', header: 'Deliver to', accessor: (p) => p.warehouse?.name || '' },
  ];

  const supplierColumns: Column<any>[] = [
    { id: 'name', header: 'Supplier', required: true, accessor: (s) => s.name, cell: (s) => <div><p className="font-semibold text-gray-900">{s.name}</p><p className="text-xs text-gray-500">{s.contactName}{s.phone ? ` · ${s.phone}` : ''}</p></div> },
    { id: 'lead', header: 'Lead time', align: 'right', accessor: (s) => s.leadTimeDays, cell: (s) => `${s.leadTimeDays} days` },
    { id: 'rating', header: 'Rating', align: 'right', accessor: (s) => Number(s.rating || 0), cell: (s) => (s.rating ? `${Number(s.rating).toFixed(1)}★` : '—') },
    { id: 'onTime', header: 'On time', align: 'right', accessor: (s) => s.onTimeRate ?? -1, cell: (s) => (s.onTimeRate == null ? '—' : <span className={s.onTimeRate >= 90 ? 'font-semibold text-success-600' : s.onTimeRate >= 70 ? 'font-semibold text-warning-600' : 'font-semibold text-error-600'}>{s.onTimeRate}%</span>) },
    { id: 'orders', header: 'Orders', align: 'right', accessor: (s) => s.orders, cell: (s) => `${s.orders}${s.openOrders ? ` (${s.openOrders} open)` : ''}` },
    { id: 'spend', header: 'Spend', align: 'right', accessor: (s) => s.spend, cell: (s) => rwf(s.spend) },
    { id: 'email', header: 'Email', defaultHidden: true, accessor: (s) => s.email || '' },
  ];

  const open = pos.filter((p) => ['DRAFT', 'SENT', 'PARTIAL'].includes(p.status));

  return (
    <div>
      <PageHeader
        title="Purchasing"
        subtitle="Purchase orders and the suppliers who fill them"
        breadcrumbs={[{ label: 'Warehouse' }]}
        icon={<FileText className="h-5 w-5" />}
        actions={
          <>
            <button onClick={() => { refresh(); refreshSuppliers(); }} className="flex h-9 w-9 items-center justify-center rounded-xl border border-gray-200 bg-white text-gray-500 shadow-sm hover:bg-gray-50" title="Refresh"><RefreshCw className="h-4 w-4" /></button>
            <Button variant="secondary" size="sm" onClick={() => post('/purchase-orders/auto-restock', {}, 'Restock orders drafted')}><Sparkles className="mr-1.5 h-4 w-4 text-accent-500" /> Auto-restock</Button>
            <Button size="sm" onClick={() => (tab === 'orders' ? setShowCreate(true) : setShowSupplier(true))}><Plus className="mr-1.5 h-4 w-4" /> {tab === 'orders' ? 'New purchase order' : 'Add supplier'}</Button>
          </>
        }
      />

      <div className="mb-5 grid grid-cols-2 gap-4 xl:grid-cols-4">
        <StatCard label="Open orders" value={open.length} icon={<Clock className="h-5 w-5" />} tone="accent" />
        <StatCard label="Waiting to send" value={pos.filter((p) => p.status === 'DRAFT').length} icon={<FileText className="h-5 w-5" />} />
        <StatCard label="On order (value)" value={open.reduce((s, p) => s + Number(p.totalAmount), 0)} prefix="RWF " compact icon={<Wallet className="h-5 w-5" />} tone="info" />
        <StatCard label="Suppliers" value={suppliers.filter((s) => s.active).length} icon={<Building2 className="h-5 w-5" />} tone="success" />
      </div>

      <div className="mb-3 flex w-fit rounded-xl bg-gray-100 p-1 text-xs font-medium">
        {([['orders', 'Purchase orders'], ['suppliers', 'Suppliers']] as const).map(([key, label]) => (
          <button key={key} onClick={() => setTab(key)} className={`rounded-lg px-3 py-1.5 transition ${tab === key ? 'bg-white text-primary-700 shadow-sm' : 'text-gray-500 hover:text-gray-800'}`}>{label}</button>
        ))}
      </div>

      {tab === 'orders' ? (
        <DataTable
          storageKey="purchase-orders"
          rows={filtered}
          columns={poColumns}
          rowKey={(p) => p.id}
          loading={loading}
          initialSort={{ id: 'number', dir: 'desc' }}
          searchPlaceholder="Search PO number or supplier…"
          activeKey={viewId}
          onRowClick={(p) => setViewId(p.id)}
          filters={<FilterChip label="Status" value={status} onChange={setStatus} options={['DRAFT', 'SENT', 'PARTIAL', 'RECEIVED', 'CANCELLED'].map((s) => ({ value: s, label: statusLabel(s) }))} />}
          toolbarRight={<ExportMenu getRows={() => filtered.map((p) => ({ PO: p.poNumber, Supplier: p.supplier?.name, Status: p.status, 'Total Amount': Number(p.totalAmount), Expected: p.expectedDate ? formatDate(p.expectedDate) : '' }))} filename="purchase-orders" title="Purchase Orders" />}
          rowActions={(p) => (
            <>
              {p.status === 'DRAFT' && <button onClick={() => post(`/purchase-orders/${p.id}/send`, {}, `${p.poNumber} sent`)} className="inline-flex h-8 items-center gap-1 rounded-lg bg-primary-500 px-2.5 text-xs font-semibold text-white"><Send className="h-3.5 w-3.5" /> Send</button>}
              {['SENT', 'PARTIAL'].includes(p.status) && <button onClick={() => setReceiving(p)} className="inline-flex h-8 items-center gap-1 rounded-lg bg-success-500 px-2.5 text-xs font-semibold text-white"><PackageCheck className="h-3.5 w-3.5" /> Receive</button>}
            </>
          )}
          empty={!pos.length ? <EmptyState title="No purchase orders yet" description="Create one, or let Auto-restock draft orders for low-stock items." /> : undefined}
        />
      ) : (
        <DataTable storageKey="suppliers" rows={suppliers} columns={supplierColumns} rowKey={(s) => s.id} loading={loadingSuppliers} searchPlaceholder="Search suppliers…" initialSort={{ id: 'spend', dir: 'desc' }} />
      )}

      <Drawer
        open={Boolean(viewing)}
        onClose={() => setViewId(null)}
        title={viewing?.poNumber || ''}
        subtitle={viewing?.supplier?.name}
        icon={<FileText className="h-4 w-4" />}
        width="lg"
        footer={viewing ? (
          <>
            {viewing.status === 'DRAFT' && <Button size="sm" onClick={() => post(`/purchase-orders/${viewing.id}/send`, {}, `${viewing.poNumber} sent`)}><Send className="mr-1.5 h-4 w-4" /> Send to supplier</Button>}
            {['SENT', 'PARTIAL'].includes(viewing.status) && <Button variant="success" size="sm" onClick={() => setReceiving(viewing)}><PackageCheck className="mr-1.5 h-4 w-4" /> Receive goods</Button>}
            {!['RECEIVED', 'CANCELLED'].includes(viewing.status) && <Button variant="secondary" size="sm" onClick={() => post(`/purchase-orders/${viewing.id}/cancel`, {}, `${viewing.poNumber} cancelled`)}><X className="mr-1.5 h-4 w-4" /> Cancel</Button>}
          </>
        ) : undefined}
      >
        {viewing && (
          <div className="space-y-5">
            <DetailHero avatar={<Truck className="h-6 w-6" />} title={viewing.poNumber} subtitle={viewing.supplier?.name} badges={<StatusBadge status={viewing.status} size="md" />} />
            <DetailSection title="Order" icon={<FileText className="h-4 w-4" />}>
              <DetailGrid>
                <DetailField label="Created">{formatDate(viewing.createdAt)}</DetailField>
                <DetailField label="Expected">{viewing.expectedDate ? formatDate(viewing.expectedDate) : '—'}</DetailField>
                <DetailField label="Deliver to">{viewing.warehouse?.name || '—'}</DetailField>
                <DetailField label="Total">{rwf(viewing.totalAmount)}</DetailField>
                {viewing.notes && <DetailField label="Notes" className="sm:col-span-2">{viewing.notes}</DetailField>}
              </DetailGrid>
            </DetailSection>
            <div className="overflow-hidden rounded-xl border border-gray-100">
              <table className="w-full text-sm">
                <thead className="bg-gray-50 text-xs uppercase tracking-wide text-gray-500"><tr><th className="px-4 py-2 text-left">Item</th><th className="px-4 py-2 text-right">Ordered</th><th className="px-4 py-2 text-right">Received</th><th className="px-4 py-2 text-right">Cost</th></tr></thead>
                <tbody className="divide-y divide-gray-50">
                  {viewing.items.map((l: any) => (
                    <tr key={l.id}><td className="px-4 py-2.5 font-medium text-gray-800">{l.item.name}</td><td className="px-4 py-2.5 text-right">{l.quantity}</td><td className={`px-4 py-2.5 text-right ${l.receivedQuantity >= l.quantity ? 'text-success-600' : 'text-gray-600'}`}>{l.receivedQuantity}</td><td className="px-4 py-2.5 text-right">{rwf(l.quantity * Number(l.unitCost))}</td></tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        )}
      </Drawer>

      <Modal isOpen={showCreate} onClose={() => setShowCreate(false)} title="New purchase order" icon={<Plus className="h-5 w-5" />} size="lg">
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
          <label className="block text-sm"><span className="mb-1 block font-medium text-gray-700">Supplier</span>
            <select value={form.supplierId} onChange={(e) => setForm({ ...form, supplierId: e.target.value })} className="h-10 w-full rounded-xl border border-gray-200 px-3 text-sm"><option value="">Choose…</option>{suppliers.filter((s) => s.active).map((s) => <option key={s.id} value={s.id}>{s.name}</option>)}</select>
          </label>
          <label className="block text-sm"><span className="mb-1 block font-medium text-gray-700">Deliver to</span>
            <select value={form.warehouseId} onChange={(e) => setForm({ ...form, warehouseId: e.target.value })} className="h-10 w-full rounded-xl border border-gray-200 px-3 text-sm"><option value="">Any</option>{warehouses.map((w) => <option key={w.id} value={w.id}>{w.name}</option>)}</select>
          </label>
          <label className="block text-sm"><span className="mb-1 block font-medium text-gray-700">Expected date</span>
            <input type="date" value={form.expectedDate} onChange={(e) => setForm({ ...form, expectedDate: e.target.value })} className="h-10 w-full rounded-xl border border-gray-200 px-3 text-sm" />
          </label>
        </div>
        <div className="mt-5 space-y-2">
          <p className="text-sm font-medium text-gray-700">Items</p>
          {form.lines.map((line, i) => (
            <div key={i} className="grid grid-cols-[minmax(0,1fr)_6rem_8rem_2.5rem] gap-2">
              <select value={line.itemId} onChange={(e) => {
                const it = items.find((x) => x.id === Number(e.target.value));
                const lines = [...form.lines];
                lines[i] = { ...line, itemId: e.target.value, unitCost: it ? Math.round(Number(it.unitPrice) * 0.72) : 0 };
                setForm({ ...form, lines });
              }} className="h-10 rounded-xl border border-gray-200 px-3 text-sm">
                <option value="">Item…</option>{items.map((it) => <option key={it.id} value={it.id}>{it.name}</option>)}
              </select>
              <input type="number" min={1} value={line.quantity} onChange={(e) => { const lines = [...form.lines]; lines[i] = { ...line, quantity: Number(e.target.value) }; setForm({ ...form, lines }); }} className="h-10 rounded-xl border border-gray-200 px-2 text-sm" placeholder="Qty" />
              <input type="number" min={0} value={line.unitCost} onChange={(e) => { const lines = [...form.lines]; lines[i] = { ...line, unitCost: Number(e.target.value) }; setForm({ ...form, lines }); }} className="h-10 rounded-xl border border-gray-200 px-2 text-sm" placeholder="Unit cost" />
              <button onClick={() => setForm({ ...form, lines: form.lines.filter((_, j) => j !== i) })} disabled={form.lines.length === 1} className="action-btn action-btn-delete h-10 w-10 disabled:opacity-30"><Trash2 className="h-4 w-4" /></button>
            </div>
          ))}
          <button onClick={() => setForm({ ...form, lines: [...form.lines, { itemId: '', quantity: 10, unitCost: 0 }] })} className="inline-flex items-center gap-1 text-xs font-semibold text-primary-600 hover:underline"><Plus className="h-3.5 w-3.5" /> Add line</button>
        </div>
        <div className="mt-5 flex items-center justify-between border-t border-gray-100 pt-4">
          <p className="text-sm text-gray-600">Total <b className="text-gray-900">{rwf(total)}</b></p>
          <div className="flex gap-2"><Button variant="secondary" size="sm" onClick={() => setShowCreate(false)}>Cancel</Button><Button size="sm" onClick={createPO}>Create draft</Button></div>
        </div>
      </Modal>

      <Modal isOpen={Boolean(receiving)} onClose={() => setReceiving(null)} title="Receive goods" subtitle={receiving?.poNumber} icon={<PackageCheck className="h-5 w-5" />}>
        {receiving && (
          <div className="space-y-3">
            <p className="text-sm text-gray-600">Stock is added to inventory{receiving.warehouse ? ` at ${receiving.warehouse.name}` : ''}. Add an expiry date for perishable items.</p>
            {receiving.items.filter((l: any) => l.receivedQuantity < l.quantity).map((l: any) => (
              <div key={l.id} className="flex items-center justify-between gap-3 rounded-xl border border-gray-100 p-3">
                <span className="text-sm"><b className="text-gray-900">{l.item.name}</b><span className="block text-xs text-gray-500">{l.quantity - l.receivedQuantity} {l.item.unit} to receive</span></span>
                <input type="date" value={expiry[l.itemId] || ''} onChange={(e) => setExpiry({ ...expiry, [l.itemId]: e.target.value })} className="h-9 rounded-lg border border-gray-200 px-2 text-xs" title="Expiry date (optional)" />
              </div>
            ))}
            <div className="flex justify-end gap-2 pt-2"><Button variant="secondary" size="sm" onClick={() => setReceiving(null)}>Cancel</Button><Button variant="success" size="sm" onClick={receive}>Receive everything</Button></div>
          </div>
        )}
      </Modal>

      <Modal isOpen={showSupplier} onClose={() => setShowSupplier(false)} title="Add supplier" icon={<Building2 className="h-5 w-5" />} size="sm">
        <div className="space-y-3">
          {([['name', 'Company name'], ['contactName', 'Contact person'], ['email', 'Email'], ['phone', 'Phone'], ['address', 'Address'], ['leadTimeDays', 'Lead time (days)']] as const).map(([key, label]) => (
            <label key={key} className="block text-sm"><span className="mb-1 block font-medium text-gray-700">{label}</span>
              <input value={supplierForm[key]} type={key === 'leadTimeDays' ? 'number' : 'text'} onChange={(e) => setSupplierForm({ ...supplierForm, [key]: e.target.value })} className="h-10 w-full rounded-xl border border-gray-200 px-3 text-sm" />
            </label>
          ))}
        </div>
        <div className="mt-5 flex justify-end gap-2"><Button variant="secondary" size="sm" onClick={() => setShowSupplier(false)}>Cancel</Button><Button size="sm" onClick={addSupplier}>Add supplier</Button></div>
      </Modal>
    </div>
  );
}
