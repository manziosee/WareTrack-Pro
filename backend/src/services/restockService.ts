import { prisma } from '../lib/prisma';
import { NotificationService } from './notificationService';

/**
 * Draft a purchase order per supplier for every item at or below its minimum
 * that isn't already on an open purchase order. Order quantity brings stock to
 * three times the minimum.
 */
export async function generateRestockOrders(createdBy?: number) {
  const items = await prisma.inventoryItem.findMany({
    where: { status: 'ACTIVE' },
    select: { id: true, name: true, quantity: true, minQuantity: true, unitPrice: true, supplier: true },
  });
  const low = items.filter((i) => i.minQuantity > 0 && i.quantity <= i.minQuantity);
  if (!low.length) return [];

  const openLines = await prisma.purchaseOrderItem.findMany({
    where: { purchaseOrder: { status: { in: ['DRAFT', 'SENT', 'PARTIAL'] } } },
    select: { itemId: true },
  });
  const alreadyOrdered = new Set(openLines.map((l) => l.itemId));
  const needed = low.filter((i) => !alreadyOrdered.has(i.id));
  if (!needed.length) return [];

  const suppliers = await prisma.supplier.findMany({ where: { active: true } });
  if (!suppliers.length) return [];
  const fallback = suppliers[0];
  const warehouse = await prisma.warehouse.findFirst({ where: { active: true }, orderBy: { id: 'asc' } });

  // Group by supplier (matched by name on the item, otherwise the first active supplier)
  const groups = new Map<number, typeof needed>();
  for (const item of needed) {
    const supplier = suppliers.find((s) => item.supplier && s.name.toLowerCase() === item.supplier.toLowerCase()) || fallback;
    groups.set(supplier.id, [...(groups.get(supplier.id) || []), item]);
  }

  let count = await prisma.purchaseOrder.count();
  const created = [];
  for (const [supplierId, list] of groups) {
    const supplier = suppliers.find((s) => s.id === supplierId)!;
    const lines = list.map((i) => ({
      itemId: i.id,
      quantity: Math.max(1, i.minQuantity * 3 - i.quantity),
      unitCost: Math.round(Number(i.unitPrice) * 0.72),
    }));
    count++;
    const po = await prisma.purchaseOrder.create({
      data: {
        poNumber: `PO-${new Date().getFullYear()}-${String(count).padStart(4, '0')}`,
        supplierId,
        warehouseId: warehouse?.id,
        status: 'DRAFT',
        autoGenerated: true,
        createdBy,
        expectedDate: new Date(Date.now() + supplier.leadTimeDays * 86400000),
        totalAmount: lines.reduce((s, l) => s + l.quantity * l.unitCost, 0),
        notes: `Auto-generated for ${list.length} low-stock item(s)`,
        items: { create: lines },
      },
    });
    created.push(po);
  }

  await NotificationService.createNotification({
    type: 'PURCHASE_ORDER',
    severity: 'INFO',
    title: 'Restock purchase orders drafted',
    message: `${created.length} draft purchase order(s) were created for ${needed.length} low-stock item(s). Review and send them to suppliers.`,
  }).catch(() => undefined);

  return created;
}
